"""基于 20260817 数据（GUI 采集，10~330g 可信段）重新拟合非线性校正系数。
链路：显示 w = A*w0 + B*w0^2，其中 w0 = raw*LSB（线性标定后）。
用最小二乘拟合 真实 = A*显示 + B*显示^2，输出新系数。
"""
import numpy as np

# (真实, 显示) —— 20260817_011234.csv 可信段（10~330g，含 210/220/230）
pairs = [
    (10, 9.90), (20, 19.97), (30, 29.91), (40, 39.95), (50, 49.99),
    (60, 60.01), (70, 70.38), (80, 80.22), (90, 90.25), (100, 100.20),
    (110, 110.33), (120, 120.35), (130, 130.39), (140, 140.40), (150, 150.75),
    (160, 160.67), (170, 171.06), (180, 180.90), (190, 190.90), (200, 201.15),
    (220, 221.36), (210, 211.44), (230, 231.54), (240, 241.86), (250, 252.64),
    (260, 262.81), (270, 272.69), (280, 282.92), (290, 293.01), (300, 303.05),
    (310, 313.35), (320, 323.41), (330, 333.43),
]
t = np.array([p[0] for p in pairs], dtype=float)
y = np.array([p[1] for p in pairs], dtype=float)

# 拟合 真实 = A*y + B*y^2（过原点）
A = np.vstack([y, y**2]).T
coef, *_ = np.linalg.lstsq(A, t, rcond=None)
A_fit, B_fit = coef
resid = t - (A_fit * y + B_fit * y**2)
print(f'拟合: 真实 = {A_fit:.6f}*显示 {B_fit:+.3e}*显示^2')
print(f'残差: max {np.abs(resid).max():+.3f} g, std {resid.std():.3f} g')
print('\n各点残差:')
for tt, yy, r in zip(t, y, resid):
    print(f'  {tt:4.0f}g -> 校正后 {tt - r:7.2f} (残差 {r:+5.2f})')

print(f'\n建议: SCALE_NL_A = {A_fit:.6f}f, SCALE_NL_B = {B_fit:.3e}f')
