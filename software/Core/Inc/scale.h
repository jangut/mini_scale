/**
 ******************************************************************************
 * @file    scale.h
 * @brief   称重模块：软件 SPI + ADS1220(24bit ADC) + 称重/滤波/去皮/标定 + 温度
 *
 * 引脚定义（与 hardware 原理图 / 引脚分配.md 一致）：
 *   PA3 = CS, PA4 = SCLK, PA5 = DRDY, PA6 = MISO, PA7 = MOSI
 *   PA1 = 温度传感器模拟输入（STM32 ADC1_IN1）
 ******************************************************************************
 */
#ifndef SCALE_H
#define SCALE_H

#include <stdint.h>

/* ------------------------------------------------------------------ */
/* 标定参数                                                           */
/* ------------------------------------------------------------------ */

/**
 * @brief 1 个 ADC 原始码（滤波后、去皮后）对应的克数。
 *
 * 标定流程（拿到整机后执行一次）：
 *   1. 空载时按去皮键（或调用 scale_tare），读 scale_raw_net() 得 raw0
 *   2. 放已知砝码 W(g)，读 scale_raw_net() 得 raw1
 *   3. 把本宏改为：SCALE_G_PER_LSB = W / (raw1 - raw0)
 *
 * 注意：ADS1220 满量程 ±2.5V（外部基准 REF5025），信号链为
 *   应变片 -> INA826(G≈989) -> ADS1220 AIN1-AIN0 差分。
 *   若应变片灵敏度使 INA826 输出超过 ±2.5V 会饱和，需核对硬件增益。
 */
#define SCALE_G_PER_LSB       1.0f

/**
 * @brief 模拟温度传感器灵敏度（mV/°C）。
 *   LM35 类 = 10；NTC 等非线性传感器需改用 scale_temp_centi 中的换算。
 */
#define TEMP_SENSOR_MV_PER_C  10

/* ------------------------------------------------------------------ */
/* 对外接口                                                            */
/* ------------------------------------------------------------------ */

void     scale_init(void);       /* 初始化软件 SPI + ADS1220（须在时钟/GPIO 之后调用） */
uint8_t  scale_update(void);     /* 采样一次并滑动平均，成功返回 1，超时返回 0 */
void     scale_tare(void);       /* 把当前读数记为去皮零点 */
int32_t  scale_raw_net(void);    /* 去皮后的原始码（int32，24bit 有符号） */
int32_t  scale_weight_centi(void); /* 重量 × 100（0.01 g 分辨率） */
int32_t  scale_temp_centi(void);   /* 温度 × 10（0.1 °C 分辨率） */

#endif /* SCALE_H */
